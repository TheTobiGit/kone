const PARSED_CACHE = new Map<string, LogoPointSet>();

export function getToolLogo(key: string): LogoPointSet {
  let parsed = PARSED_CACHE.get(key);
  if (!parsed) {
    const raw = RAW_TOOL_LOGOS[key] || RAW_TOOL_LOGOS["tools"]!;
    parsed = {
      version: 1,
      n: raw.n,
      p: Float32Array.from(raw.p),
      e: Float32Array.from(raw.e),
      style: raw.style,
      shell: raw.shell,
    };
    PARSED_CACHE.set(key, parsed);
  }
  return parsed;
}

