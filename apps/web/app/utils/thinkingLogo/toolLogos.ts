export function logoForHugeIcon(icon?: HugeIcon | null): LogoPointSet | null {
  if (!icon) return null;
  return HUGEICON_TO_TOOL_LOGO.get(icon) ?? null;
}

export function logoForToolFamily(family?: ToolOrbFamily | "thinking" | "working"): LogoPointSet {
  if (family === "thinking") return THINKING_LOGO;
  if (family === "working") return WORKING_LOGO;
  if (family && TOOL_FAMILY_LOGOS[family]) return TOOL_FAMILY_LOGOS[family];
  return TOOL_FAMILY_LOGOS.neutral;
}
