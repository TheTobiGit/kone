// Rebuild the checked-in catalog from the same packages used by apps/web.
const fs = require('fs');
const collection = require('@iconify-json/vscode-icons/icons.json');
const tables = ['FileNamesToIcon', 'FileExtensions1ToIcon', 'FileExtensions2ToIcon', 'LanguagesToIcon'];
const maps = tables.map(name => require(`vscode-icons-js/dist/generated/${name}`)[name]);
const normalize = value => value.replace(/\.svg$/, '').replaceAll('_', '-').replace(/^file-type-pdf$/, 'file-type-pdf2');
const overrides = ['default-file','file-type-docker','file-type-bundler','file-type-cargo','file-type-bun','file-type-poetry','file-type-pip','file-type-turbo','file-type-svelte','file-type-license','file-type-dotenv','file-type-graphql','file-type-protobuf'];
const names = [...new Set([...maps.flatMap(map => Object.values(map).map(normalize)), ...overrides])].sort();
const quote = s => JSON.stringify(s);
const indices = new Map(names.map((name, i) => [name, i]));
let out = '// Generated by scripts/generate-file-icons.cjs; do not edit.\nuse rune::Icon;\n\n';
out += 'pub(super) static ICONS: &[Icon] = &[\n';
for (const name of names) {
  const item = collection.icons[name];
  let body = item?.body ?? ''; // Iconify also renders nothing for an unknown name.
  const width = item?.width ?? collection.width, height = item?.height ?? collection.height;
  if (width !== 32 || height !== 32) {
    const scale = 32 / Math.max(width, height), x = (32 - width * scale) / 2, y = (32 - height * scale) / 2;
    body = `<g transform="translate(${x} ${y}) scale(${scale})">${body}</g>`;
  }
  out += `    Icon { name: ${quote(name)}, view: 32.0, body: ${quote(body)} },\n`;
}
out += '];\n';
for (let i = 0; i < tables.length; i++) {
  out += `pub(super) static ${['FILENAMES','EXTENSIONS','DOUBLE_EXTENSIONS','LANGUAGES'][i]}: &[(&str, usize)] = &[\n`;
  for (const [key, value] of Object.entries(maps[i]).sort(([a],[b]) => a < b ? -1 : a > b ? 1 : 0)) out += `    (${quote(key)}, ${indices.get(normalize(value))}),\n`;
  out += '];\n';
}
out += 'pub(super) static NAMES: &[&str] = &[\n' + names.map(n => `    ${quote(n)},\n`).join('') + '];\n';
fs.writeFileSync('apps/rune/src/ui/file_icons_data.rs', out);
